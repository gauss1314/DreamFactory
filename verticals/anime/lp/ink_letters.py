def line_width(text):
    x = 0
    for i, c in enumerate(text):
        x += SPACE if c == ' ' else G[c][0] + KERN.get((c, text[i + 1] if i + 1 < len(text) else ''), 0)
    return x


def line_strokes(text, sc, ox, oy, seed=21, shear=-.14, wt=1.0):
    """[(Stroke, t0, t1)] in 0..1 writing time; repeated letters are each drawn a little differently"""
    r = np.random.default_rng(seed)
    out, x = [], 0.
    drift = 0.
    for i, c in enumerate(text):
        if c == ' ':
            x += SPACE * (1 + r.normal(0, .05)); continue
        adv, strokes = G[c]
        kx, ky, rot = 1 + r.normal(0, .025), 1 + r.normal(0, .025), r.normal(0, .02)
        drift = drift * .7 + r.normal(0, 1.5)
        sw = 1 + r.normal(0, .06)
        for q in strokes:
            jit = r.normal(0, 1.7, (len(q), 2))
            jit[[0, -1]] *= 1.6
            P = []
            for (u, (jx, jy)) in zip(q, jit):
                ux, uy = u[0] * kx + jx, u[1] * ky + jy + drift
                ux, uy = ux - rot * uy, uy + rot * ux
                P.append(((ux + x + shear * uy) * sc + ox, uy * sc + oy, u[2] * sc * sw * wt * (1 + r.normal(0, .05))) + tuple(u[3:]))
            k = i / (len(text) - 1.)
            reload = .85 - .5 * ((i % 13) / 13.)                    # dips the brush now and then
            out.append((P, reload, int(r.integers(1, 9999))))
        x += adv + KERN.get((c, text[i + 1] if i + 1 < len(text) else ''), 0) + r.normal(0, 1.5)
    S = [Stroke(P, step=.5, entry=.9, load=(ld, ld * .8), tip=1.0, seed=sd, dry=.5, wet=.8) for P, ld, sd in out]
    L = np.array([s.S[-1] + 8 * sc for s in S]); c = np.r_[0, np.cumsum(L)] / L.sum()
    return [(s, c[j], c[j] + (c[j + 1] - c[j]) * .9) for j, s in enumerate(S)]


