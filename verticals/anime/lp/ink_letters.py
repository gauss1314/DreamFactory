def seal_mask(w, h, seed=3, ss=3):
    """ink coverage 0..1 of the vermilion seal 作品 (two characters stacked), hand carved, imperfectly inked"""
    W_, H_ = w * ss, h * ss
    sf = cairo.ImageSurface(cairo.FORMAT_A8, W_, H_); c = cairo.Context(sf)
    r = np.random.default_rng(seed)
    m = .045 * w
    def rr(x0, y0, x1, y1, rad, amp):
        pts = []
        for (cx, cy, a0) in ((x1 - rad, y0 + rad, -90), (x1 - rad, y1 - rad, 0), (x0 + rad, y1 - rad, 90), (x0 + rad, y0 + rad, 180)):
            for a in np.linspace(a0, a0 + 90, 7): pts.append((cx + rad * math.cos(math.radians(a)), cy + rad * math.sin(math.radians(a))))
        q = resample(np.vstack([pts, pts[:1]]), 5.0)
        return spl(q + r.normal(0, amp, q.shape), closed=True, n=3)
    def poly(P):
        c.new_path(); c.move_to(*P[0])
        for q in P[1:]: c.line_to(*q)
        c.close_path()
    k = ss
    poly(rr(m, m, w - m, h - m, .085 * w, .35) * k); c.set_source_rgba(1, 1, 1, 1); c.fill()
    c.set_operator(cairo.OPERATOR_CLEAR)
    # inner white frame line of an intaglio seal is left out: solid ground, carved characters
    bx = .12 * w; bw = w - 2 * bx; bh = (h - 2 * .085 * h) / 2 - .012 * h
    for j, chars in enumerate(_seal_strokes()):
        oy = .085 * h + j * (bh + .024 * h)
        for P, hw in chars:
            q = np.array(P, float); q = np.c_[bx + q[:, 0] / 100 * bw, oy + q[:, 1] / 100 * bh]
            q = q + r.normal(0, .25, q.shape)
            R = ribbon(spl(q, n=8), 2 * hw / 100 * bw * .98, taper=(.10, .12), press=.16, seed=seed * 31 + int(P[0][0] * 7 + P[0][1]), tremor=.5, tmin=.62)
            poly(R * k); c.fill()
    sf.flush()
    a = np.ndarray((H_, sf.get_stride()), np.uint8, sf.get_data())[:, :W_].astype(f32) / 255.
    a = cv2.resize(a, (w, h), interpolation=cv2.INTER_AREA)
    # cinnabar paste: mottled, starved at one corner, chipped edges, squeezed darker rim
    n1 = fbm(h, w, (26, 9), (1, .7), seed + 5); n2 = fbm(h, w, (3.4, 1.8), (1, .8), seed + 6)
    x, y = np.meshgrid(np.linspace(0, 1, w), np.linspace(0, 1, h))
    starve = .10 + .42 * smooth(.55, 1.25, x * .75 + y * .62) + .22 * smooth(.5, 0., x + y * .9)
    cov = smooth(starve - .55, starve + .25, .42 + .20 * n1 + .16 * n2)
    e = cv2.GaussianBlur(a, (0, 0), 1.6)
    rim = np.clip((1 - e) * 2.2, 0, 1) * a
    cf = fbm(h, w, (9, 4), (1, .5), seed + 8)
    chip = smooth(1.75, 2.15, cf + .95 * rim + .35 * smooth(.6, 1.2, x * .7 + y * .6)) + smooth(2.35, 2.7, np.abs(cf))
    out = a * (.50 + .50 * cov) * (1 - .85 * chip) + .16 * rim * a * cov
    return np.clip(out, 0, 1).astype(f32)


